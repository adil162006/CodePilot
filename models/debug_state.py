from typing import TypedDict, Annotated, Any, Literal
from langgraph.graph.message import add_messages
from pydantic import Field, BaseModel, field_validator


class FileManifest(BaseModel):
    path: str = Field(description="Relative path of the file within the project.")
    absolute_path: str = Field(description="Absolute path of the file within the project.")
    extension: str = Field(description="Extension of the file within the project.")
    language: str = Field(description="Programming language of the file.")
    size: int = Field(description="File size in bytes.")


class BugFinding(BaseModel):
    file_name: str = Field(
        description="Relative path of the file containing the bug."
    )
    absolute_path: str = Field(
        description="Absolute path of the file containing the bug."
    )
    line_number: int = Field(ge=1)
    severity: Literal["low", "medium", "high", "critical"]
    explanation: str
    suggested_fixes: list[str] = Field(default_factory=list)


class BugFindingCandidate(BaseModel):
    """LLM response schema before the node attaches file metadata."""
    line_number: int = Field(ge=1)
    severity: Literal["low", "medium", "high", "critical"]
    explanation: str
    suggested_fixes: list[str] = Field(default_factory=list)


class BugFindResponse(BaseModel):
    findings: list[BugFindingCandidate] = Field(
        default_factory=list,
        description="All genuine bugs found in the source code. Empty if none."
    )


class ProposedPatch(BaseModel):
    bug_identifier: str = Field(
        ..., description="Identifier of the bug"
    )
    target_file_path: str = Field(
        ..., description="Relative path of the target file"
    )
    bug_summary: str
    root_cause: str

    # Python generates this field after receiving the LLM response.
    proposed_code_change: str = Field(
        default="",
        description="Unified Git diff generated by Python"
    )

    corrected_file_content: str = Field(
        ...,
        description="Complete corrected source file"
    )

    explanation: str
    assumptions: list[str] = Field(default_factory=list)
    risk: list[str] = Field(default_factory=list)
    generated: bool
    failure: str = ""

    approved: bool = False

    @field_validator("assumptions", "risk", mode="before")
    @classmethod
    def normalize_list_fields(cls, value):
        if isinstance(value, str):
            return [value] if value.strip() else []
        return value


class ProposedPatchResponse(BaseModel):
    solutions: list[ProposedPatch] = Field(
        default_factory=list,
        description="List of solutions found in the source code."
    )


class ValidationSchema(BaseModel):
    bug_identifier: str = Field(..., description="Identifier of the bug that was proposed")
    patch_valid: bool = Field(..., description="Whether the patch was valid.")
    syntax_valid: bool | None = Field(..., description="Whether the syntax was valid.")
    # tests_passed: bool | None = Field(..., description="Whether tests passed or failed.")
    validation_errors: list[str] = Field(..., description="Errors from applying the patch or validating it")
    validation_status: Literal["passed", "failed", "error"] = Field(...,
                                                                    description="Overall result, such as passed, failed, or skipped")


# Main Graph State
class DebuggingState(BaseModel):
    # Project information
    project_root: str = Field(
        description="Absolute path to the project working directory."
    )

    file_manifest: list[FileManifest] = Field(
        default_factory=list,
        description="Files discovered during project scanning."
    )

    # Conversation history
    messages: Annotated[list, add_messages] = Field(
        default_factory=list,
        description="Messages exchanged during the debugging workflow."
    )

    # Bug analysis
    bug_findings: list[BugFinding] = Field(
        default_factory=list,
        description="Potential or confirmed bugs identified in source files."
    )

    bugs_analysis_errors: list[dict[str, Any]] = Field(
        default_factory=list,
        description="Errors encountered while analyzing source files."
    )

    # Patch generation
    proposed_patches: list[ProposedPatch] = Field(
        default_factory=list,
        description="Proposed code changes generated for identified bugs."
    )

    proposed_patches_analysis_errors: list[dict[str, str]] = Field(
        default_factory=list,
        description="Errors encountered while generating proposed patches."
    )

    # Patch validation
    validation_results: list[ValidationSchema] = Field(
        default_factory=list,
        description="Validation results for individual proposed patches."
    )

    validation_errors: list[dict[str, str]] = Field(
        default_factory=list,
        description="Unexpected errors encountered during patch validation."
    )

    # Test execution
    test_results: dict[str, Any] = Field(
        default_factory=dict,
        description="Results from executing project tests."
    )

    # Workflow tracking
    debug_attempts: int = Field(
        default=0,
        description="Number of fix attempts completed."
    )

    iteration_after_apply_patch: int = Field(
        default=0,
        description="numbers of iteration after applying the patch. "
    )

    debug_status: Literal[
        "pending",
        "analyzing",
        "no_issues",
        "patch_generation_completed",
        "patch_validation_completed",
        "applying",
        "passed",
        "unresolved",
        "error",
    ] = Field(
        default="pending",
        description="Current status of the debugging workflow."
    )

    debugging_report: str = Field(
        default="",
        description="Final report summarizing findings, patches, and test results."
    )
